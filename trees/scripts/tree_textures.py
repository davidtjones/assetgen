"""Tree textures: bark and foliage, drawn separately so either can change
without the other.

A species has two texture sets, each a colour image and a normal map (bark
has a third image):

- **Bark** (`bark`): 512 x 1024, tiling both ways, covering 1 m round the
  trunk and 2 m up it, with a third image packing occlusion, roughness and
  metalness. A bark kind is either drawn here or taken from a material made
  by the textures project (`GENERATED`). The mesh wraps it a whole number of times round each
  branch, so thick trunks and thin limbs keep about the same texel size.
- **Foliage** (`foliage`): 1024 x 1024 holding four cards in a 2 x 2 grid, each
  512 x 512, drawn growing upward from the bottom centre of its cell. Alpha is
  the cut-out.

Foliage colour is stored *relative*, not absolute. A texel holds how much
brighter, darker, yellower or bluer that bit of leaf is than the tree's leaf
colour: mid grey (0.5 in linear light) means "exactly the leaf colour". The
game multiplies by the tree's leaf colour (and by two), so one set of cards
serves green, gold and red trees alike. `tone` does the encoding.

Normal maps are tangent space, OpenGL convention (green = up the image), the
same as the ground textures.

Everything is drawn here with numpy noise and PIL; nothing is photographed or
generated by a model.
"""

import math
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw
from scipy import ndimage

from textures.scripts import tex_core as tc

BARK_W, BARK_H = 512, 1024
BARK_METRES = (1.0, 2.0)      # what one bark tile covers: round the trunk, up it
ATLAS = 1024
CARD = 512                    # one foliage card, pixels square
SS = 2                        # cards are drawn this much larger, then reduced


def card_rect(i: int) -> tuple[float, float, float, float]:
    """UV rect `(u0, v0, u1, v1)` of foliage card `i` (0..3); v0 is the top.
    Inset by a texel so neighbouring cards do not bleed in."""
    x0, y0 = (i % 2) * CARD, (i // 2) * CARD
    e = 1.0
    return (x0 + e) / ATLAS, (y0 + e) / ATLAS, (x0 + CARD - e) / ATLAS, (y0 + CARD - e) / ATLAS


def _srgb(c):
    c = np.clip(np.asarray(c, np.float32), 0, 1)
    return np.where(c <= 0.0031308, c * 12.92, 1.055 * c ** (1 / 2.4) - 0.055)


def tone(m) -> tuple[int, int, int]:
    """Encode a leaf tone - red, green, blue as multiples of the tree's leaf
    colour - as an 8-bit texel. (1, 1, 1) is the leaf colour itself."""
    return tuple(int(v) for v in np.round(_srgb(np.asarray(m, np.float32) * 0.5) * 255))


# --- bark -------------------------------------------------------------------------

def _squeeze(a: np.ndarray) -> np.ndarray:
    """Noise is built square (1024 x 1024) so it tiles; squeeze it to the bark
    tile's 512 columns."""
    return a.reshape(a.shape[0], BARK_W, 2, *a.shape[2:]).mean(2)


def _bark(kind: str, seed: int):
    """Colour (sRGB float) and height (0..1) of one bark tile, both 1024 x 512."""
    n = BARK_H
    S = lambda i: (seed, i)  # noqa: E731
    grain = tc.spectral(n, S(9), beta=0.6, lo=60, hi=n / 2.1, stretch=(1.0, 3.0))
    if kind == "birch" or kind == "aspen":
        # Smooth pale bark: fine horizontal lines, dark lens-shaped scars.
        base = tc.spectral(n, S(1), beta=2.0, lo=2, hi=30)
        lines = tc.spectral(n, S(2), beta=0.5, lo=30, hi=220, stretch=(14.0, 1.0))
        dashes = tc.smoothstep(0.68, 0.80, lines)
        if kind == "birch":
            scars = tc.smoothstep(0.70, 0.80, tc.spectral(n, S(3), beta=1.9, lo=3, hi=22, stretch=(3.0, 1.0)))
            rough = tc.smoothstep(0.62, 0.9, tc.spectral(n, S(4), beta=1.4, lo=2, hi=9, stretch=(1.0, 2.0)))
            peel = tc.spectral(n, S(5), beta=1.0, lo=10, hi=120, stretch=(8.0, 1.0))
            t = (0.80 + 0.16 * base) * (1 - 0.6 * dashes) * (1 - 0.9 * scars) * (0.9 + 0.14 * peel)
            t = t * (1 - 0.55 * rough * grain)
            rgb = tc.ramp(np.clip(t, 0, 1), [(0.0, (0.06, 0.05, 0.045)), (0.45, (0.42, 0.38, 0.33)),
                                              (0.8, (0.84, 0.82, 0.77)), (1.0, (0.95, 0.94, 0.90))])
            height = 0.7 - 0.25 * dashes - 0.5 * scars * (0.5 + grain) - 0.3 * rough * grain + 0.08 * peel
        else:
            eyes = tc.smoothstep(0.76, 0.84, tc.spectral(n, S(3), beta=2.2, lo=3, hi=16, stretch=(2.2, 1.0)))
            warts = tc.smoothstep(0.74, 0.86, tc.spectral(n, S(4), beta=1.0, lo=14, hi=70, stretch=(2.0, 1.0)))
            t = (0.74 + 0.20 * base) * (1 - 0.35 * dashes) * (1 - 0.92 * eyes) * (1 - 0.6 * warts)
            rgb = tc.ramp(np.clip(t, 0, 1), [(0.0, (0.05, 0.05, 0.045)), (0.4, (0.36, 0.36, 0.30)),
                                              (0.75, (0.72, 0.74, 0.62)), (1.0, (0.88, 0.89, 0.80))])
            # A green cast where the bark is clean: aspen bark photosynthesises.
            green = tc.spectral(n, S(6), beta=2.2, lo=1, hi=8)[..., None]
            rgb = rgb * (1 + (np.array([-0.04, 0.03, -0.08], np.float32)) * green)
            height = 0.7 - 0.15 * dashes - 0.5 * eyes * (0.4 + grain) - 0.35 * warts
        return rgb, tc.norm01(tc.blur(height, 0.8))

    if kind == "spruce" or kind == "pine":
        # Scales and plates: cells with cracks between them.
        cells = 30 if kind == "spruce" else 10
        wob = tc.spectral(n, S(1), beta=2.0, lo=3, hi=40)
        f1, f2, _, value = tc.worley(n, cells, S(2), jitter=0.95)
        f1 = tc.warp(f1, (wob - 0.5) * 30, (tc.spectral(n, S(3), beta=2.0, lo=3, hi=40) - 0.5) * 30)
        f2 = tc.warp(f2, (wob - 0.5) * 30, (tc.spectral(n, S(3), beta=2.0, lo=3, hi=40) - 0.5) * 30)
        value = tc.warp(value, (wob - 0.5) * 30, (tc.spectral(n, S(3), beta=2.0, lo=3, hi=40) - 0.5) * 30)
        edge = tc.smoothstep(0.03, 0.30 if kind == "spruce" else 0.22, f2 - f1)
        layers = tc.spectral(n, S(4), beta=1.2, lo=8, hi=90, stretch=(1.0, 2.5))
        height = edge * (0.55 + 0.3 * value + 0.15 * layers) + 0.12 * grain
        if kind == "spruce":
            stops = [(0.0, (0.07, 0.05, 0.045)), (0.45, (0.26, 0.20, 0.18)), (0.8, (0.40, 0.34, 0.31)),
                     (1.0, (0.52, 0.47, 0.44))]
        else:
            stops = [(0.0, (0.08, 0.045, 0.035)), (0.4, (0.33, 0.19, 0.12)), (0.75, (0.58, 0.38, 0.25)),
                     (1.0, (0.72, 0.55, 0.42))]
        rgb = tc.ramp(tc.norm01(height), stops)
        rgb = rgb * (0.86 + 0.28 * value[..., None])
        return rgb, tc.norm01(tc.blur(height, 0.7))

    if kind == "dead":
        # Barkless weathered wood: long grain, long cracks.
        fibre = tc.spectral(n, S(1), beta=1.0, lo=20, hi=260, stretch=(1.0, 24.0))
        crack = tc.cracks(n, S(2), lo=4, hi=30, width=0.035, stretch=(1.0, 12.0))
        stain = tc.spectral(n, S(3), beta=2.2, lo=1, hi=10, stretch=(1.0, 3.0))
        height = tc.norm01(0.6 * fibre + 0.25 * stain - 0.9 * crack)
        t = np.clip(0.25 + 0.55 * fibre + 0.3 * (stain - 0.5) - 0.8 * crack, 0, 1)
        rgb = tc.ramp(t, [(0.0, (0.10, 0.09, 0.085)), (0.5, (0.44, 0.42, 0.40)), (1.0, (0.72, 0.71, 0.68))])
        return rgb, height

    # Furrowed bark (oak, and the default): ridges up the trunk split by deep
    # furrows, broken across at intervals.
    body = tc.spectral(n, S(1), beta=1.5, lo=6, hi=120, stretch=(1.0, 5.0))
    # Ridges are the high ground of a streaky noise; the furrows between them
    # are wide and deep, and wander and merge as they go up.
    streak = tc.spectral(n, S(2), beta=1.0, lo=9, hi=30, stretch=(1.0, 7.0))
    ridge = tc.smoothstep(0.30, 0.46, streak)
    # Short breaks across a ridge, where the bark has cracked as the trunk grew.
    cross = tc.smoothstep(0.80, 0.88, tc.spectral(n, S(3), beta=0.4, lo=20, hi=90, stretch=(4.0, 1.0))) * ridge
    height = tc.norm01(tc.blur(ridge * (0.62 + 0.38 * body) - 0.45 * cross, 1.2) + 0.08 * grain)
    cav = tc.cavity(height, 7.0)
    t = np.clip(height * 1.05 - 0.45 * cav + 0.22 * (grain - 0.5), 0, 1)
    rgb = tc.ramp(t, [(0.0, (0.07, 0.055, 0.045)), (0.3, (0.24, 0.20, 0.17)), (0.7, (0.42, 0.37, 0.32)),
                      (1.0, (0.56, 0.52, 0.46))])
    # Lichen on the ridge tops, moss in broad patches.
    lichen = tc.smoothstep(0.62, 0.8, tc.spectral(n, S(5), beta=1.6, lo=4, hi=50)) * tc.smoothstep(0.55, 0.8, height)
    rgb = rgb + (np.array([0.56, 0.60, 0.52], np.float32) - rgb) * (0.55 * lichen[..., None])
    moss = tc.smoothstep(0.64, 0.86, tc.spectral(n, S(6), beta=2.2, lo=1, hi=12)) * 0.5
    rgb = rgb + (np.array([0.20, 0.27, 0.10], np.float32) - rgb) * moss[..., None]
    return rgb, height


# How deep each bark's relief is, as `tex_core.normal_map` takes it.
_RELIEF = {"oak": 9.0, "spruce": 6.0, "pine": 8.0, "birch": 2.5, "aspen": 2.0, "dead": 5.0}


# Bark kinds that take their tile from a generated material instead of the
# drawing code above: kind -> (a candidate under `textures/out/`, and the
# colour its average is graded to, sRGB). `mat/` candidates come from
# `pixi run material <name>`, `sm/` ones from the older `pixi run material-sm`.
# The models get the relief of bark right more often than its colour, which
# runs orange, so only the pattern is kept and the colour is set here.
GENERATED = {
    "oak": ("mat/bark_oak_s2", (104, 92, 80)),
    "pine": ("sm/bark_pine_s4_paint", (150, 96, 66)),
    "spruce": ("mat/bark_spruce_s0", (96, 80, 72)),
    "aspen": ("sm/bark_aspen_s5", (196, 198, 176)),
    "dead": ("mat/bark_dead_s0", (150, 146, 138)),
}
MATERIALS = Path(__file__).resolve().parents[2] / "textures" / "out"
# Bark kinds that can grow moss: kind -> the mossy variant of its `GENERATED`
# material (an `edit_of` entry in the textures project, so the two line up).
MOSSY = {"oak": "mat/bark_oak_mossy_s2"}


def _orm(height: np.ndarray, roughness: np.ndarray) -> np.ndarray:
    """Pack occlusion (red), roughness (green) and metalness (blue, none) the
    way glTF and the game's material read them. Occlusion is how deep a texel
    sits in the bark's furrows."""
    occlusion = 1.0 - 0.85 * tc.cavity(height, 5.0)
    return np.stack([occlusion, roughness, np.zeros_like(height)], -1)


def _generated(name: str, colour) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """A generated material as a bark tile. Its square tile covers a metre
    each way, so it is stacked twice up the 1 x 2 m bark tile."""
    load = lambda f: np.asarray(Image.open(MATERIALS / name / f).convert("RGB").resize(  # noqa: E731
        (BARK_W, BARK_W), Image.LANCZOS)).astype(np.float32) / 255.0
    albedo, normal = load("albedo.png"), load("normal.png")
    orm = _orm(load("height.png")[..., 0], load("roughness.png")[..., 0])
    rgb = tc.recolour(albedo, np.asarray(colour, np.float32) / 255.0, contrast=1.15)
    opaque = np.full((BARK_H, BARK_W, 1), 255, np.uint8)
    stack = lambda a: np.concatenate([tc.to8(np.tile(a, (2, 1, 1))), opaque], -1)  # noqa: E731
    return stack(rgb), stack(normal), stack(orm)


def moss(kind: str) -> tuple[np.ndarray] | None:
    """The mossy overlay for a bark kind, uint8 RGBA the size of its bark
    tile, or None if it has none. Colour is the mossy variant's, shifted the
    way the bark's own colour was graded so the wood under the moss matches.
    Alpha is the bark's height, so the game can let moss take the furrows
    before the ridges."""
    if kind not in MOSSY or kind not in GENERATED:
        return None
    base, mossy = MATERIALS / GENERATED[kind][0], MATERIALS / MOSSY[kind]
    if not (base.exists() and mossy.exists()):
        return None
    load = lambda d, f: np.asarray(Image.open(d / f).convert("RGB").resize(  # noqa: E731
        (BARK_W, BARK_W), Image.LANCZOS)).astype(np.float32) / 255.0
    graded = _generated(*GENERATED[kind])[0][:BARK_W, :, :3].astype(np.float32) / 255.0
    gain = graded.mean((0, 1)) / np.maximum(load(base, "albedo.png").mean((0, 1)), 1e-6)
    rgba = np.concatenate([load(mossy, "albedo.png") * gain, load(base, "height.png")[..., :1]], -1)
    return (tc.to8(np.tile(rgba, (2, 1, 1))),)


def bark(kind: str, seed: int = 0) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """One bark tile: colour, normal map, and occlusion / roughness /
    metalness, each uint8 RGBA, 1024 rows x 512."""
    if kind in GENERATED and (MATERIALS / GENERATED[kind][0]).exists():
        return _generated(*GENERATED[kind])
    rgb, height = _bark(kind, seed + 100)
    rgb, height = _squeeze(rgb), _squeeze(height)
    normal = tc.normal_map(height, _RELIEF.get(kind, 6.0))
    opaque = np.full((BARK_H, BARK_W, 1), 255, np.uint8)
    # Drawn bark: ridges are worn smoother than the furrows between them.
    orm = _orm(height, 0.95 - 0.2 * height)
    return tuple(np.concatenate([tc.to8(a), opaque], -1) for a in (rgb, normal, orm))


# --- foliage cards ----------------------------------------------------------------

def _flat(n):
    """A unit normal as an 8-bit normal-map texel."""
    n = np.asarray(n, np.float32)
    n = n / max(float(np.linalg.norm(n)), 1e-6)
    return tuple(int(v) for v in np.round((n * 0.5 + 0.5) * 255))


UPRIGHT = _flat((0, 0, 1))


class Card:
    """Two supersampled canvases drawn in step, colour and normal, with y up and
    the origin at the bottom centre. Colours are leaf tones (see `tone`)."""

    def __init__(self):
        self.size = CARD * SS
        self.colour = Image.new("RGBA", (self.size, self.size), (0, 0, 0, 0))
        self.normal = Image.new("RGB", (self.size, self.size), UPRIGHT)
        self.dc = ImageDraw.Draw(self.colour)
        self.dn = ImageDraw.Draw(self.normal)

    def xy(self, p):
        return (self.size / 2 + p[0] * SS, self.size - 1 - p[1] * SS)

    def line(self, a, b, m, width, n=UPRIGHT):
        w = max(1, int(round(width * SS)))
        self.dc.line([self.xy(a), self.xy(b)], fill=tone(m) + (255,), width=w)
        self.dn.line([self.xy(a), self.xy(b)], fill=n, width=w)

    def poly(self, pts, m, n=UPRIGHT):
        pts = [self.xy(p) for p in pts]
        self.dc.polygon(pts, fill=tone(m) + (255,))
        self.dn.polygon(pts, fill=n)

    def finish(self) -> tuple[np.ndarray, np.ndarray]:
        """The card as uint8 RGBA colour and RGBA normal, `CARD` square."""
        colour = np.asarray(self.colour.resize((CARD, CARD), Image.LANCZOS)).copy()
        normal = np.asarray(self.normal.resize((CARD, CARD), Image.BOX)).astype(np.float32) / 127.5 - 1.0
        # Flood colour and normal into the transparent texels (nearest opaque),
        # so filtering and mips never pull in black or a flat normal.
        solid = colour[..., 3] > 96
        if solid.any():
            idx = ndimage.distance_transform_edt(~solid, return_distances=False, return_indices=True)
            colour[..., :3] = colour[..., :3][idx[0], idx[1]]
            normal = normal[idx[0], idx[1]]
        normal /= np.maximum(np.linalg.norm(normal, axis=-1, keepdims=True), 1e-6)
        out = np.full((CARD, CARD, 4), 255, np.uint8)
        out[..., :3] = tc.to8(normal * 0.5 + 0.5)
        return colour, out


def _vary(rng, light, spread=0.05):
    """A leaf tone: `light` times a small random shift toward yellow or blue."""
    w = rng.normal(0, spread)
    return (light * (1 + w), light, light * (1 - 1.6 * w))


TWIG = (0.42, 0.34, 0.30)


def _needles(card, a, b, rng, length, density=1.0, spread=62.0, width=1.0):
    """Needles along the twig a->b, both sides, angled toward the tip."""
    ax, ay = a
    dx, dy = b[0] - ax, b[1] - ay
    seg = math.hypot(dx, dy)
    if seg < 1e-3:
        return
    ux, uy = dx / seg, dy / seg
    count = max(1, int(seg / 1.9 * density))
    for i in range(count):
        t = (i + rng.random()) / count
        px, py = ax + dx * t, ay + dy * t
        for side in (-1, 1):
            ang = math.radians(spread + rng.normal(0, 9)) * side
            ca, sa = math.cos(ang), math.sin(ang)
            nx, ny = ux * ca - uy * sa, ux * sa + uy * ca
            ln = length * (0.75 + 0.5 * rng.random()) * (1.0 - 0.35 * t)
            m = _vary(rng, 0.62 + 0.75 * rng.random(), 0.04)
            # A needle tilts to its own side of the twig.
            card.line((px, py), (px + nx * ln, py + ny * ln), m, width,
                      _flat((nx * 0.5 + rng.normal(0, 0.2), ny * 0.5 + rng.normal(0, 0.2), 1.0)))


def spruce_card(seed: int, droop: float = 0.0):
    """A spruce bough: a spine with side twigs sweeping forward, all needled.
    `droop` > 0 gives the hanging secondary sprays of an older branch."""
    rng = np.random.default_rng(seed)
    card = Card()
    top = CARD - 14
    half = CARD / 2
    spine = [(math.sin(y / 90.0 + seed) * 7.0, y) for y in np.linspace(4, top, 40)]
    # Side twigs, longest a third of the way up, drawn from the base outward so
    # the tip overlaps what is behind it.
    n_side = 28
    for i in range(n_side):
        t = (i + 0.5) / n_side
        k = int(t * (len(spine) - 2))
        base = spine[k]
        reach = (half * 0.94) * (math.sin(math.pi * min(t * 1.25 + 0.12, 1.0)) ** 0.8) * (0.8 + 0.3 * rng.random())
        side = -1 if i % 2 else 1
        ang = math.radians(48 + 14 * rng.random() - 20 * t)
        tip = (base[0] + side * reach * math.sin(ang), base[1] + reach * math.cos(ang) - droop * reach * 0.5)
        mid = ((base[0] + tip[0]) / 2 + side * 3, (base[1] + tip[1]) / 2 + 5 - droop * reach * 0.12)
        card.line(base, mid, TWIG, 1.8)
        card.line(mid, tip, TWIG, 1.3)
        _needles(card, base, mid, rng, 12, density=1.25)
        _needles(card, mid, tip, rng, 11, density=1.25)
        # Tertiary sprigs.
        for s in range(3):
            f = 0.3 + 0.25 * s
            p = (base[0] + (tip[0] - base[0]) * f, base[1] + (tip[1] - base[1]) * f)
            q = (p[0] + side * 20 * rng.random() + rng.normal(0, 5), p[1] + 20 + 12 * rng.random() - droop * 30)
            _needles(card, p, q, rng, 9, density=1.1)
    for a, b in zip(spine[:-1], spine[1:]):
        card.line(a, b, TWIG, 2.8)
        _needles(card, a, b, rng, 11, density=1.0)
    return card.finish()


def pine_card(seed: int):
    """Pine: long needles in round tufts at the ends of a forking twig."""
    rng = np.random.default_rng(seed)
    card = Card()

    def tuft(p, r):
        # Keep the whole tuft on the card.
        r = min(r, CARD / 2 - abs(p[0]) - 4, CARD - p[1] - 4)
        for _ in range(int(190 * r / 60)):
            ang = rng.uniform(0, 2 * math.pi)
            ln = r * (0.6 + 0.4 * rng.random())
            c, s = math.cos(ang), math.sin(ang)
            card.line(p, (p[0] + c * ln, p[1] + s * ln * 0.9 + ln * 0.15), _vary(rng, 0.6 + 0.8 * rng.random(), 0.04),
                      1.1, _flat((c * 0.6, s * 0.6, 1.0)))

    def grow(p, ang, ln, depth):
        q = (p[0] + math.sin(ang) * ln, p[1] + math.cos(ang) * ln)
        card.line(p, q, TWIG, 1.6 + depth * 1.2)
        if depth == 0:
            tuft(q, 58 + 20 * rng.random())
            return
        for _ in range(2 + (rng.random() < 0.5)):
            grow(q, ang + rng.normal(0, 0.5), ln * (0.6 + 0.2 * rng.random()), depth - 1)
        tuft(q, 42)

    grow((0, 2), rng.normal(0, 0.06), 150, 2)
    return card.finish()


def _outline(shape: str, s: float) -> float:
    """Half-width of a leaf, as a fraction of its length, `s` of the way from
    its base to its tip."""
    if shape == "oak":
        return 0.30 * math.sin(math.pi * s ** 0.9) ** 0.6 * (1 + 0.42 * math.sin(2 * math.pi * 3.5 * s - 0.6))
    if shape == "round":
        return 0.50 * math.sin(math.pi * min(s, 1.0) ** 0.72) ** 0.62
    return 0.40 * math.sin(math.pi * s ** 0.62) ** 0.9  # ovate, pointed


def _leaf(card, p, ang, size, m, shape, rng):
    """One leaf at `p` pointing along `ang` (radians from +y), `size` long. It
    is drawn as two halves folded a little along the midrib, each with its own
    tone and normal, so a leaf catches the light as a leaf does."""
    along = (math.sin(ang), math.cos(ang))
    across = (math.cos(ang), -math.sin(ang))
    steps = 14 if shape == "oak" else 9
    left, right = [p], [p]
    for i in range(1, steps):
        s = i / steps
        w = max(_outline(shape, s), 0.0) * size
        q = (p[0] + along[0] * s * size, p[1] + along[1] * s * size)
        left.append((q[0] - across[0] * w, q[1] - across[1] * w))
        right.append((q[0] + across[0] * w, q[1] + across[1] * w))
    tip = (p[0] + along[0] * size, p[1] + along[1] * size)
    # The whole leaf tilts some way; its halves fold up from the midrib.
    tilt = rng.normal(0, 0.32, 2)
    fold = 0.34
    for pts, sign, light in ((left, -1.0, 0.94), (right, 1.0, 1.06)):
        n = (tilt[0] - sign * across[0] * fold, tilt[1] - sign * across[1] * fold, 1.0)
        card.poly(pts + [tip], tuple(c * light for c in m), _flat(n))
    card.line(p, tip, tuple(c * 1.22 for c in m), 0.8, _flat((tilt[0], tilt[1], 1.0)))


def leaf_card(seed: int, shape: str, leaf: float, count: int, hang: float = 0.0, stems: int = 3):
    """A broadleaf spray: forking twigs carrying overlapping leaves, each
    `leaf` pixels long. `hang` pulls the outer twigs downward (birch)."""
    rng = np.random.default_rng(seed)
    card = Card()
    tips = []
    reach = CARD * 0.36

    def grow(p, ang, ln, depth):
        q = (p[0] + math.sin(ang) * ln, p[1] + math.cos(ang) * ln - hang * ln * (2 - depth) * 0.25)
        card.line(p, q, TWIG, 1.0 + depth * 1.1)
        for f in np.linspace(0.2, 1.0, 5):
            tips.append(((p[0] + (q[0] - p[0]) * f, p[1] + (q[1] - p[1]) * f), ang))
        if depth > 0:
            for _ in range(3):
                grow(q, ang + rng.normal(0, 0.62), ln * (0.6 + 0.25 * rng.random()), depth - 1)

    for a0 in np.linspace(-0.5, 0.5, stems):
        grow((0, 2), a0 + rng.normal(0, 0.12), reach * (0.9 + 0.25 * rng.random()), 2)
    # Leaves, darkest first so the bright ones sit on top.
    leaves = []
    edge = CARD / 2 - leaf * 0.75
    for _ in range(count * 3):
        if len(leaves) >= count:
            break
        (p, ang) = tips[rng.integers(len(tips))]
        q = (p[0] + rng.normal(0, leaf * 0.5), p[1] + rng.normal(0, leaf * 0.5))
        turn = ang + rng.normal(0, 0.9) + (math.pi * hang * 0.6 if rng.random() < hang else 0)
        end = (q[0] + math.sin(turn) * leaf, q[1] + math.cos(turn) * leaf)
        if max(abs(q[0]), abs(end[0])) > edge or not (leaf * 0.3 < min(q[1], end[1]) and max(q[1], end[1]) < CARD - leaf * 0.6):
            continue
        leaves.append((rng.random(), q, turn))
    for shade, q, ang in sorted(leaves):
        _leaf(card, q, ang, leaf * (0.8 + 0.4 * rng.random()), _vary(rng, 0.50 + 0.95 * shade), shape, rng)
    return card.finish()


def dead_card(seed: int):
    """Bare twigs."""
    rng = np.random.default_rng(seed)
    card = Card()

    def grow(p, ang, ln, depth):
        q = (p[0] + math.sin(ang) * ln, p[1] + math.cos(ang) * ln)
        card.line(p, q, tuple(0.8 + 0.5 * rng.random() for _ in range(3)), 1.2 + depth * 1.2)
        if depth > 0:
            for _ in range(2 + (rng.random() < 0.6)):
                grow(q, ang + rng.normal(0, 0.6), ln * (0.55 + 0.25 * rng.random()), depth - 1)

    grow((0, 2), 0.0, 190, 3)
    return card.finish()


# name -> a function of (seed, card index) giving one card.
FOLIAGE = {
    "spruce": lambda s, i: spruce_card(s + i, droop=(0.0, 0.0, 0.55, 0.9)[i]),
    "pine": lambda s, i: pine_card(s + i),
    "oak": lambda s, i: leaf_card(s + i, "oak", 46, 105),
    "birch": lambda s, i: leaf_card(s + i, "ovate", 30, 190, hang=0.35 + 0.1 * i),
    "aspen": lambda s, i: leaf_card(s + i, "round", 31, 150, hang=0.15),
    "bush": lambda s, i: leaf_card(s + 40 + i, "ovate", 44, 95, hang=0.1),
    "twigs": lambda s, i: dead_card(s + i),
}


def foliage(kind: str, seed: int = 0) -> tuple[np.ndarray, np.ndarray]:
    """The four cards of one foliage kind: colour and normal atlases, uint8
    RGBA, 1024 x 1024."""
    colour = np.zeros((ATLAS, ATLAS, 4), np.uint8)
    normal = np.full((ATLAS, ATLAS, 4), 255, np.uint8)
    normal[..., :3] = UPRIGHT
    for i in range(4):
        c, n = FOLIAGE[kind](seed * 10, i)
        x0, y0 = (i % 2) * CARD, (i // 2) * CARD
        colour[y0:y0 + CARD, x0:x0 + CARD] = c
        normal[y0:y0 + CARD, x0:x0 + CARD] = n
    return colour, normal
